// Bundles the bridge and eufy-sdk (with its JavaScript dependencies) into one ES module, which
// RIoT2.Net.Devices embeds: ../Services/EufySdk/eufy-sdk-bridge.mjs. Commit the result; CI rebuilds it and fails
// when it differs.
import { build } from "esbuild";
import { builtinModules } from "node:module";
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outfile = join(here, "..", "Services", "EufySdk", "eufy-sdk-bridge.mjs");
const sdkPackage = JSON.parse(readFileSync(join(here, "node_modules", "@mega-yfue", "eufy-sdk", "package.json"), "utf8"));

const result = await build({
  entryPoints: [join(here, "src", "main.mjs")],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node24",
  // Native (WebRTC, HomeBase S1 Pro only): eufy-sdk loads it on first use and reports that it is missing.
  external: ["node-datachannel"],
  define: { EUFY_SDK_VERSION: JSON.stringify(sdkPackage.version) },
  plugins: [bundleProtobufjs()],
  // Bundled CommonJS dependencies require Node built-ins.
  banner: {
    js: [
      `// RIoT2 eufy-sdk bridge with @mega-yfue/eufy-sdk ${sdkPackage.version}. Generated by EufySdkBridge/build.mjs: do not edit.`,
      'import { createRequire as __bridgeCreateRequire } from "node:module";',
      "const require = __bridgeCreateRequire(import.meta.url);",
    ].join("\n"),
  },
  legalComments: "none",
  minify: true,
  charset: "utf8",
  metafile: true,
  write: false,
  logLevel: "warning",
});

const code = result.outputFiles[0].text;
checkRuntimeImports(code);
writeFileSync(outfile, code + licenses(result.metafile), { encoding: "utf8" });
console.log(`${relative(process.cwd(), outfile)}: ${(Buffer.byteLength(code) / 1024 / 1024).toFixed(2)} MB, eufy-sdk ${sdkPackage.version}`);

/**
 * eufy-sdk loads protobufjs with `createRequire(import.meta.url)`, which resolves next to the running file: the
 * bundle runs from the node's data folder, where no node_modules is. Make it a plain require, which esbuild bundles.
 */
function bundleProtobufjs() {
  const lookup = 'requireFrom("protobufjs")';
  return {
    name: "bundle-protobufjs",
    setup(b) {
      b.onLoad({ filter: /[\\/]@mega-yfue[\\/]eufy-sdk[\\/]dist[\\/]index\.js$/ }, (args) => {
        const source = readFileSync(args.path, "utf8");
        if (!source.includes(lookup)) throw new Error(`eufy-sdk no longer contains ${lookup}: review how it loads protobufjs`);
        return { contents: source.replaceAll(lookup, 'require("protobufjs")'), loader: "js" };
      });
    },
  };
}

/** The bundle may load only Node built-ins and node-datachannel at run time. */
function checkRuntimeImports(code) {
  const builtins = new Set(builtinModules);
  const loaded = new Set();
  for (const m of code.matchAll(/\b(?:require|import)\(\s*"([^"]+)"\s*\)|\bfrom\s*"([^"]+)"/g)) loaded.add(m[1] ?? m[2]);
  const foreign = [...loaded].filter((name) => !builtins.has(name.replace(/^node:/, "")) && name !== "node-datachannel");
  if (foreign.length) throw new Error(`the bundle loads modules it doesn't contain: ${foreign.join(", ")}`);
}

/** The license texts of every package in the bundle, as a trailing comment, so they ship with the code. */
function licenses(metafile) {
  const packages = new Map();
  for (const input of Object.keys(metafile.inputs)) {
    const match = /^(.*node_modules[\\/](?:@[^\\/]+[\\/])?[^\\/]+)[\\/]/.exec(input);
    if (!match) continue;
    const dir = join(here, match[1]);
    if (packages.has(dir)) continue;
    const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    const file = existsSync(dir) ? readdirSync(dir).sort().find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f)) : undefined;
    const text = file ? readFileSync(join(dir, file), "utf8").replace(/\r\n/g, "\n").trim() : `License: ${pkg.license ?? "unknown"}`;
    packages.set(dir, { name: `${pkg.name}@${pkg.version}`, license: pkg.license, text });
  }
  const sections = [...packages.values()]
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((p) => `${p.name} (${p.license ?? "see below"})\n\n${p.text.replaceAll("*/", "* /")}`);
  return `\n/*\nThird-party software in this bundle:\n\n${sections.join("\n\n----------------------------------------\n\n")}\n*/\n`;
}
